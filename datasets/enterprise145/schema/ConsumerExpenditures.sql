-- Schema for database: ConsumerExpenditures

CREATE TABLE `EXPENDITURES` (
  `EXPENDITURE_ID` varchar(11) NOT NULL,
  `HOUSEHOLD_ID` varchar(10) NOT NULL,
  `YEAR` int(11) NOT NULL,
  `MONTH` int(11) NOT NULL,
  `PRODUCT_CODE` varchar(6) NOT NULL,
  `COST` double NOT NULL,
  `GIFT` int(11) NOT NULL,
  `IS_TRAINING` int(255) NOT NULL DEFAULT 1 COMMENT 'Designed split to trainin and testing set',
  PRIMARY KEY (`EXPENDITURE_ID`) USING BTREE,
  KEY `HOUSEHOLD_ID` (`HOUSEHOLD_ID`),
  CONSTRAINT `EXPENDITURES_ibfk_1` FOREIGN KEY (`HOUSEHOLD_ID`) REFERENCES `HOUSEHOLDS` (`HOUSEHOLD_ID`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci
;


CREATE TABLE `HOUSEHOLDS` (
  `HOUSEHOLD_ID` varchar(10) NOT NULL,
  `YEAR` int(11) NOT NULL,
  `INCOME_RANK` double NOT NULL,
  `INCOME_RANK_1` double NOT NULL,
  `INCOME_RANK_2` double NOT NULL,
  `INCOME_RANK_3` double NOT NULL,
  `INCOME_RANK_4` double NOT NULL,
  `INCOME_RANK_5` double NOT NULL,
  `INCOME_RANK_MEAN` double NOT NULL,
  `AGE_REF` int(11) NOT NULL,
  PRIMARY KEY (`HOUSEHOLD_ID`) USING BTREE,
  KEY `HOUSEHOLD_ID_idx` (`HOUSEHOLD_ID`,`YEAR`) USING BTREE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci
;


CREATE TABLE `HOUSEHOLD_MEMBERS` (
  `HOUSEHOLD_ID` varchar(10) NOT NULL,
  `YEAR` int(11) NOT NULL,
  `MARITAL` varchar(1) NOT NULL,
  `SEX` varchar(1) NOT NULL,
  `AGE` int(11) NOT NULL,
  `WORK_STATUS` varchar(2) DEFAULT NULL,
  KEY `HOUSEHOLD_ID` (`HOUSEHOLD_ID`),
  CONSTRAINT `HOUSEHOLD_MEMBERS_ibfk_1` FOREIGN KEY (`HOUSEHOLD_ID`) REFERENCES `HOUSEHOLDS` (`HOUSEHOLD_ID`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci
;

