CREATE TABLE `ACCOUNTS` (
  `ACC_KEY` int(255) NOT NULL,
  `ACCTP_KEY` int(255) DEFAULT NULL,
  `PROD_KEY` int(255) DEFAULT NULL,
  `ORG_KEY` int(255) DEFAULT NULL,
  `PT_UNIFIED_KEY` bigint(255) DEFAULT NULL,
