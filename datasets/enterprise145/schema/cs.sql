  KEY `PROD_KEY` (`PROD_KEY`) USING BTREE,
  KEY `ORG_KEY` (`ORG_KEY`) USING BTREE,
  KEY `PT_UNIFIED_KEY` (`PT_UNIFIED_KEY`) USING BTREE,
  CONSTRAINT `ACCOUNTS_ibfk_1` FOREIGN KEY (`ACCTP_KEY`) REFERENCES `ACCOUNT_TYPES` (`ACCTP_KEY`) ON DELETE CASCADE ON UPDATE CASCADE,
