#!/usr/bin/env python3
"""Generate the LaTeX skeleton of Table VII (``tab:e1_s2t``) from LOCAL E1 metrics.

Reads every ``metrics.json`` (written by ``experiments/E1/evaluate.py``) below the given
``--metrics-dir`` directories and writes ``table_vii.tex`` into ``--out-dir``.  The script has no
built-in scores: cells without a local metrics file are printed as ``--``; text metrics of
Enterprise-145 are ``N/A``.  Output goes only below ``--out-dir`` (git-ignored by default).
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Sequence

ROOT = Path(__file__).resolve().parents[2]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from src import datasets_io as dio  # noqa: E402
from src import inference_clients as ic  # noqa: E402
from src import repro_io as rio  # noqa: E402

DEFAULT_METRICS_DIR = ROOT / "experiments" / "E1" / "outputs" / "metrics"
DEFAULT_OUT_DIR = ROOT / "experiments" / "E1" / "outputs" / "latex_generated"
MODEL_LABELS = {
    "codellama13b": "CodeLlama-13B", "llama31": "Llama-3.1-8B", "deepseek": "DeepSeek-Coder-6.7B",
    "sonnet46": "Claude Sonnet 4.6", "gpt54mini": "GPT-5.4-mini",
}
PROMPT_LABELS = {"basic": "B", "detailed": "D"}
COLUMNS = (("bleu4", "BLEU-4", 2), ("rougeL", "ROUGE-L", 3), ("bertscore_f1", "BERTScore", 3), ("scr_macro", "SCR", 3))


def load_metrics(dirs: Sequence[str | Path]) -> dict[tuple[str, str, str], dict]:
    """``{(dataset, model, prompt): metrics_json}`` from all E1 ``metrics.json`` files (later wins)."""
    out: dict[tuple[str, str, str], dict] = {}
    for d in dirs:
        for p in sorted(Path(d).rglob("metrics.json")):
            try:
                m = json.loads(p.read_text(encoding="utf-8"))
            except Exception:  # noqa: BLE001
                continue
            if isinstance(m, dict) and m.get("experiment") == "E1" and m.get("metrics") is not None:
                out[(m["dataset"], m["model"], m["prompt"])] = m
    return out


def cell(m: dict | None, key: str, digits: int) -> str:
    if m is None:
        return "--"
    if key in (m.get("not_applicable") or []):
        return "N/A"
    v = m["metrics"].get(key)
    return "--" if v is None else f"{v:.{digits}f}"


def build_table_vii(records: dict[tuple[str, str, str], dict], *, datasets: Sequence[str] = rio.DATASETS,
                    models: Sequence[str] = ic.DESCRIBER_KEYS) -> str:
    lines = [
        "% GENERATED by experiments/E1/generate_table_vii.py from local metrics -- do not commit.",
        "% '--' = no local metrics file for that cell; 'N/A' = metric undefined (Enterprise-145 has no gold text).",
        r"\begin{table*}[t]", r"\centering",
        r"\caption{Schema-to-text quality (E1). B = basic, D = detailed describer prompt.}",
        r"\label{tab:e1_s2t}",
        r"\begin{tabular}{llcccccc}", r"\toprule",
        r"Dataset & Model & Prompt & " + " & ".join(c[1] for c in COLUMNS) + r" & $N$ \\",
        r"\midrule",
    ]
    for di, d in enumerate(datasets):
        if di:
            lines.append(r"\midrule")
        label = dio.DATASET_LABELS[d]
        first = True
        for m in models:
            for p in rio.PROMPT_VARIANTS:
                rec = records.get((d, m, p))
                n = "--" if rec is None else f"{rec['n_scored']}/{rec['n_gold']}"
                cells = [cell(rec, k, dg) for k, _, dg in COLUMNS]
                lines.append(" & ".join([label if first else "", MODEL_LABELS.get(m, m), PROMPT_LABELS[p], *cells, n]) + r" \\")
                first = False
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table*}", ""]
    return "\n".join(lines)


def build_parser() -> argparse.ArgumentParser:
    ap = argparse.ArgumentParser(description="LaTeX Table VII skeleton from local E1 metrics JSON (no baked-in scores).")
    ap.add_argument("--metrics-dir", nargs="+", default=[str(DEFAULT_METRICS_DIR)],
                    help="one or more directories searched recursively for metrics.json "
                         "(default experiments/E1/outputs/metrics/)")
    ap.add_argument("--out-dir", default=None,
                    help="output directory for table_vii.tex (default experiments/E1/outputs/latex_generated/)")
    return ap


def main(argv: Sequence[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    try:
        out_dir = rio.assert_ignored_out_dir(args.out_dir or DEFAULT_OUT_DIR)
    except ValueError as e:
        print(f"error: {e}", file=sys.stderr)
        return 2
    records = load_metrics(args.metrics_dir)
    tex = build_table_vii(records)
    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / "table_vii.tex"
    path.write_text(tex, encoding="utf-8")
    print(f"found {len(records)} metrics file(s); wrote {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
