#!/usr/bin/env python3
"""Generate the LaTeX skeleton of Table VIII (``tab:e2_roundtrip``) from LOCAL E2 metrics.

Reads every ``metrics.json`` (written by ``experiments/E2/evaluate.py``) below ``--metrics-dir``
and writes ``table_viii.tex`` into ``--out-dir``.  No built-in scores: cells without a local
metrics file are printed as ``--``.  Output goes only below ``--out-dir`` (git-ignored by default).
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Sequence

ROOT = Path(__file__).resolve().parents[2]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from src import datasets_io as dio  # noqa: E402
from src import inference_clients as ic  # noqa: E402
from src import repro_io as rio  # noqa: E402
from src.metrics import ELEMENTS  # noqa: E402

DEFAULT_METRICS_DIR = ROOT / "experiments" / "E2" / "outputs" / "metrics"
DEFAULT_OUT_DIR = ROOT / "experiments" / "E2" / "outputs" / "latex_generated"
MODEL_LABELS = {
    "codellama13b": "CodeLlama-13B", "llama31": "Llama-3.1-8B", "deepseek": "DeepSeek-Coder-6.7B",
    "sonnet46": "Claude Sonnet 4.6", "gpt54mini": "GPT-5.4-mini",
}
PROMPT_LABELS = {"basic": "B", "detailed": "D"}
ELEMENT_LABELS = {"tables": "Tab.", "attributes": "Attr.", "domain": "Dom.", "entity": "Ent.", "referential": "Ref."}


def load_metrics(dirs: Sequence[str | Path]) -> dict[tuple[str, str, str], dict]:
    """``{(dataset, describer, prompt): metrics_json}`` from all E2 ``metrics.json`` files (later wins)."""
    out: dict[tuple[str, str, str], dict] = {}
    for d in dirs:
        for p in sorted(Path(d).rglob("metrics.json")):
            try:
                m = json.loads(p.read_text(encoding="utf-8"))
            except Exception:  # noqa: BLE001
                continue
            if isinstance(m, dict) and m.get("experiment") == "E2" and m.get("metrics") is not None:
                out[(m["dataset"], m["describer_model"], m["prompt"])] = m
    return out


def build_table_viii(records: dict[tuple[str, str, str], dict], *, datasets: Sequence[str] = rio.DATASETS,
                     models: Sequence[str] = ic.DESCRIBER_KEYS) -> str:
    lines = [
        "% GENERATED by experiments/E2/generate_table_viii.py from local metrics -- do not commit.",
        "% '--' = no local metrics file for that cell.",
        r"\begin{table*}[t]", r"\centering",
        r"\caption{Round-trip fidelity (E2): micro-F1 per element and mean nGED. Constructor: GPT-4o-mini. "
        r"B = basic, D = detailed describer prompt.}",
        r"\label{tab:e2_roundtrip}",
        r"\begin{tabular}{llcccccccc}", r"\toprule",
        r"Dataset & Describer & Prompt & " + " & ".join(ELEMENT_LABELS[e] for e in ELEMENTS) + r" & nGED & $N$ \\",
        r"\midrule",
    ]
    for di, d in enumerate(datasets):
        if di:
            lines.append(r"\midrule")
        first = True
        for m in models:
            for p in rio.PROMPT_VARIANTS:
                rec = records.get((d, m, p))
                if rec is None:
                    cells, n = ["--"] * (len(ELEMENTS) + 1), "--"
                else:
                    f1 = rec["metrics"]["micro_f1"]
                    cells = [f"{f1[e]:.3f}" for e in ELEMENTS] + [f"{rec['metrics']['mean_nged']:.3f}"]
                    n = f"{rec['n_scored']}/{rec['n_gold']}"
                lines.append(" & ".join([dio.DATASET_LABELS[d] if first else "",
                                         MODEL_LABELS.get(m, m), PROMPT_LABELS[p], *cells, n]) + r" \\")
                first = False
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table*}", ""]
    return "\n".join(lines)


def build_parser() -> argparse.ArgumentParser:
    ap = argparse.ArgumentParser(description="LaTeX Table VIII skeleton from local E2 metrics JSON (no baked-in scores).")
    ap.add_argument("--metrics-dir", nargs="+", default=[str(DEFAULT_METRICS_DIR)],
                    help="one or more directories searched recursively for metrics.json "
                         "(default experiments/E2/outputs/metrics/)")
    ap.add_argument("--out-dir", default=None,
                    help="output directory for table_viii.tex (default experiments/E2/outputs/latex_generated/)")
    return ap


def main(argv: Sequence[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    try:
        out_dir = rio.assert_ignored_out_dir(args.out_dir or DEFAULT_OUT_DIR)
    except ValueError as e:
        print(f"error: {e}", file=sys.stderr)
        return 2
    records = load_metrics(args.metrics_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / "table_viii.tex"
    path.write_text(build_table_viii(records), encoding="utf-8")
    print(f"found {len(records)} metrics file(s); wrote {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
